# Declare and initialize
zahl = 10                   # integer
kommazahl = 10.5            # float
text = "Hello, World!"      # string
wahrheitswert = True        # boolean

# Output
print("zahl(Integer): ", zahl)
print("kommazahl(Float): ", kommazahl)
print("text(String): ", text)
print("wahrheitswert(Boolean): ", wahrheitswert)

# Check the type
print("Type of zahl: ", type(zahl))
print("Type of kommazahl: ", type(kommazahl))
print("Type of text: ", type(text))
print("Type of wahrheitswert: ", type(wahrheitswert))